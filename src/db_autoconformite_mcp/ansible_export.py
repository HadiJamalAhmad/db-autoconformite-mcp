"""Export the baseline and the inventory to Ansible: one source of truth for check and fix.

    uv run fleetctl ansible-export            # -> ansible/generated/inventory.yml

The playbook (ansible/standard-config.yml) applies exactly the `standard` values of the
baseline and revokes superuser from roles the CMDB does not allow. Nothing is typed twice,
so the checker and the remediation tool cannot drift apart.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from db_autoconformite_mcp.models import Instance, Rule

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = ROOT / "ansible" / "generated"

# Which baseline rule each standard parameter enforces (used by the cross-check).
PARAMETER_RULE = {"log_connections": "R01", "archive_mode": "R02",
                  "password_encryption": "R03", "idle_in_transaction_session_timeout": "R06"}


def standard_settings(rules: list[Rule], engine: str = "postgresql") -> dict[str, str]:
    out: dict[str, str] = {}
    for r in rules:
        for param, value in r.standard.get(engine, {}).items():
            if param in out:
                raise ValueError(f"parameter {param} standardised by two rules")
            out[param] = value
    return out


def inventory(instances: dict[str, Instance], rules: list[Rule]) -> dict:
    hosts = {}
    for inst in sorted(instances.values(), key=lambda i: i.id):
        if inst.engine != "postgresql" or not inst.in_scope:
            continue  # Oracle: no maintained Ansible collection; fixes stay SQL proposals
        hosts[inst.id] = {"ansible_connection": "local", "pg_host": inst.host,
                          "pg_port": inst.port, "pg_db": inst.service,
                          "pg_allowed_admins": list(inst.allowed_admins)}
    return {"all": {"children": {"postgresql": {
        "hosts": hosts,
        "vars": {"pg_standard_settings": standard_settings(rules)}}}}}


def write(instances: dict[str, Instance], rules: list[Rule], out: Path = DEFAULT_OUT) -> Path:
    out.mkdir(parents=True, exist_ok=True)
    path = out / "inventory.yml"
    header = "# Generated by `fleetctl ansible-export` from baseline/ and fleet/. Do not edit.\n"
    path.write_text(header + yaml.safe_dump(inventory(instances, rules), sort_keys=True,
                                            allow_unicode=True), encoding="utf-8")
    return path
